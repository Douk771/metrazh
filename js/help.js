export function renderHelp(root, sectionId) {
  root.innerHTML = `
    <main class="help-screen">
      <a class="btn ghost" href="#/">← Объекты</a>
      <h1>Как это работает</h1>
      <nav class="help-toc">${SECTIONS.map((s) => `<a href="#/help/${s.id}">${s.title}</a>`).join('')}</nav>
      ${SECTIONS.map((s) => `<section class="help-section" id="help-${s.id}"><h2>${s.title}</h2>${s.html}</section>`).join('')}
    </main>`;
  const target = sectionId && root.querySelector(`#help-${CSS.escape(sectionId)}`);
  if (target) target.scrollIntoView();
  else window.scrollTo(0, 0);
}
