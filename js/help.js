const tocLinks = (sections) => sections.map((s) => `<a href="#/help/${s.id}">${s.title}</a>`).join('');
const plainText = (s) => `${s.title} ${s.html.replace(/<[^>]+>/g, ' ')}`.toLowerCase();

export function renderHelp(root, sectionId) {
  window.scrollTo(0, 0);
  const section = SECTIONS.find((s) => s.id === sectionId);
  if (section) {
    root.innerHTML = `
      <main class="help-screen">
        <a class="btn ghost" href="#/">← Объекты</a>
        <a class="btn ghost" href="#/help">Все разделы</a>
        <section class="help-section" id="help-${section.id}"><h1>${section.title}</h1>${section.html}</section>
      </main>`;
    return;
  }
  // Общий рассказ: коротко о приложении, подробности — по разделам и через поиск.
  root.innerHTML = `
    <main class="help-screen">
      <a class="btn ghost" href="#/">← Объекты</a>
      <section class="help-section">
        <h1>Что такое Метраж</h1>
        <p>Помощник риелтора: планировка с площадями, обработка фото, текст объявления и презентация объекта.
          Всё делается прямо на устройстве и хранится на нём же.</p>
        <p>На каждом экране вверху есть знак <b>?</b> — он открывает подсказку именно про этот раздел.</p>
        <p>Обзор возможностей со скриншотами и частыми вопросами — на странице <a href="about.html">«О Метраже»</a>.</p>
        <label class="field">Поиск по справке<input id="help-search" type="search" placeholder="Например: водяной знак"></label>
        <nav class="help-toc" id="help-toc">${tocLinks(SECTIONS)}</nav>
      </section>
    </main>`;
  const toc = root.querySelector('#help-toc');
  root.querySelector('#help-search').oninput = (e) => {
    const q = e.target.value.trim().toLowerCase();
    const found = SECTIONS.filter((s) => plainText(s).includes(q));
    toc.innerHTML = found.length ? tocLinks(found) : '<p class="muted">Ничего не нашлось. Попробуйте другое слово.</p>';
  };
}
